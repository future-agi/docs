// @ts-check
/**
 * Copy the generated platform SDK reference out of a futureagi-sdk checkout.
 *
 *   node scripts/sync-sdk-reference.mjs --from ../futureagi-sdk
 *
 * The SDK repository generates `docs/sdk-reference/` (one MDX page per resource, an
 * overview, and `navigation.json`) from its API contract with `python sdkgen/generate.py`.
 * This script replaces `src/pages/docs/sdk/reference/` with those pages and rewrites
 * `src/lib/sdk-reference.mjs`, the sidebar group `navigation.ts` imports. Never edit the
 * copied pages by hand: fix the generator in the SDK repository and sync again.
 * `.github/workflows/sdk-reference-sync.yml` runs this for the SDK commit chosen by
 * `scripts/sdk-reference-release.mjs` and opens or updates one PR per SDK release.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGES_DIR = path.join(ROOT, 'src/pages/docs/sdk/reference');
const NAV_FILE = path.join(ROOT, 'src/lib/sdk-reference.mjs');

const args = process.argv.slice(2);
const fromIndex = args.indexOf('--from');
if (fromIndex === -1 || !args[fromIndex + 1]) {
  console.error('usage: node scripts/sync-sdk-reference.mjs --from <path to a futureagi-sdk checkout>');
  process.exit(2);
}
const source = path.resolve(args[fromIndex + 1], 'docs/sdk-reference');
const navSource = path.join(source, 'navigation.json');
if (!fs.existsSync(path.join(source, 'index.mdx')) || !fs.existsSync(navSource)) {
  console.error(`${source} does not hold a generated reference (index.mdx + navigation.json); run python sdkgen/generate.py in the SDK checkout first`);
  process.exit(1);
}

/** @type {{group: string, icon?: string, items: {title: string, href?: string, items?: {title: string, href: string}[]}[]}} */
const nav = JSON.parse(fs.readFileSync(navSource, 'utf-8'));
const pages = fs.readdirSync(source).filter((name) => name.endsWith('.mdx')).sort();

// Every nav item must have a page and every page a nav item, or the sidebar and the site drift.
/** @param {{href?: string, items?: any[]}[]} items */
function* walk(items) {
  for (const item of items) {
    if (item.href) yield item.href;
    if (item.items) yield* walk(item.items);
  }
}
const hrefs = new Set(walk(nav.items));
for (const page of pages) {
  const href = page === 'index.mdx' ? '/docs/sdk/reference' : `/docs/sdk/reference/${page.replace(/\.mdx$/, '')}`;
  if (!hrefs.has(href)) {
    console.error(`${page} is not in navigation.json`);
    process.exit(1);
  }
  hrefs.delete(href);
}
if (hrefs.size) {
  console.error(`navigation.json lists pages that do not exist: ${[...hrefs].join(', ')}`);
  process.exit(1);
}

fs.mkdirSync(PAGES_DIR, { recursive: true });
let removed = 0;
for (const name of fs.readdirSync(PAGES_DIR)) {
  if (name.endsWith('.mdx') && !pages.includes(name)) {
    fs.unlinkSync(path.join(PAGES_DIR, name));
    removed++;
  }
}
for (const page of pages) {
  fs.copyFileSync(path.join(source, page), path.join(PAGES_DIR, page));
}

const navModule = `// @ts-check
/**
 * Sidebar group for the platform SDK reference. Generated by
 * scripts/sync-sdk-reference.mjs from the SDK repository's docs/sdk-reference/navigation.json;
 * do not edit. navigation.ts places it in the SDK tab and scripts/audit-links.mjs audits it.
 *
 * @type {{group: string, icon?: string, items: ReadonlyArray<{title: string, href?: string, items?: ReadonlyArray<{title: string, href: string}>}>}}
 */
export const sdkReferenceNavigation = ${JSON.stringify(nav, null, 2)};
`;
fs.writeFileSync(NAV_FILE, navModule);

console.log(`sdk reference: ${pages.length} pages copied, ${removed} stale removed, ${[...walk(nav.items)].length} nav links`);
