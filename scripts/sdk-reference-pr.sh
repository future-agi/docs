#!/usr/bin/env bash
# Open, update, finish or skip the docs PR for one SDK release, from the synced working tree.
#
# Called by .github/workflows/sdk-reference-sync.yml after scripts/sync-sdk-reference.mjs has
# written the pages, with the resolver's decision in the environment (see
# scripts/sdk-reference-release.mjs): SHA REF PY TS BACKEND BRANCH STAGE PUBLISH SOURCE.
# Needs `gh` (GH_TOKEN set) and `git`; scripts/sdk-reference-pr.test.mjs runs it against fakes.
#
# State rules, so that reordered or retried dispatch events cannot leave a PR in the wrong state:
#   - PUBLISH=ready   : the PR must end up ready for review. A draft is promoted; the promotion is
#                       verified, and a failure to promote fails this run.
#   - PUBLISH=draft   : a NEW PR is opened as a draft. An EXISTING PR that is already ready belongs
#                       to a released revision that the registries confirmed; a later candidate
#                       event is stale or reordered, so it is IGNORED: neither the branch, nor the
#                       title/body, nor the state change. The run says so and exits 0.
#   - no diff vs main : nothing to open; an open PR for this release is closed (main carries it).
# Every state the script reports is read back from GitHub after acting, never assumed.
set -euo pipefail

for var in SHA PY TS BACKEND BRANCH STAGE PUBLISH; do
  [ -n "${!var:-}" ] || { echo "::error::$var is not set" >&2; exit 2; }
done
: "${REF:=$SHA}"
: "${SOURCE:=manual run}"
short=${SHA:0:12}
sdk="https://github.com/future-agi/futureagi-sdk"
pages="src/pages/docs/sdk/reference src/lib/sdk-reference.mjs"

# The open PR for this release, if any: "<number> <true|false>" (isDraft) or empty.
existing() {
  gh pr list --head "$BRANCH" --base main --state open --json number,isDraft \
    --jq '.[0] | select(. != null) | "\(.number) \(.isDraft)"'
}
state_of() {
  gh pr view "$1" --json isDraft --jq '.isDraft'
}

read -r number is_draft <<< "$(existing || true)"
number=${number:-}
is_draft=${is_draft:-}

# shellcheck disable=SC2086
if git diff --quiet -- $pages; then
  if [ -z "$number" ]; then
    echo "main already carries the reference of futureagi-sdk@$short; nothing to open"
    exit 0
  fi
  gh pr close "$number" --delete-branch \
    --comment "main already carries the reference generated by futureagi-sdk@$short; nothing left to merge."
  echo "future-agi/docs#$number closed: main already carries this reference"
  exit 0
fi

if [ "$PUBLISH" = draft ] && [ -n "$number" ] && [ "$is_draft" = false ]; then
  echo "::notice::future-agi/docs#$number for python-v$PY / typescript-v$TS is already ready for review" \
       "(a released revision the registries confirmed); ignoring this stale $STAGE event for $short." \
       "Neither the branch nor the PR was changed."
  echo "future-agi/docs#$number (unchanged: ready, stale $STAGE event ignored)"
  exit 0
fi

git config user.name "futureagi-release-bot[bot]"
git config user.email "futureagi-release-bot[bot]@users.noreply.github.com"
git switch -c "$BRANCH"
# shellcheck disable=SC2086
git add $pages
git commit -q -m "docs(sdk): sync the platform SDK reference from futureagi-sdk@$short" \
  -m "Python $PY, TypeScript $TS, backend contract $BACKEND ($STAGE)."
# One branch per release: a retry or the candidate -> released transition rewrites it.
git push --force origin "$BRANCH"

case "$STAGE" in
  released)
    title="docs(sdk): platform SDK reference for python-v$PY / typescript-v$TS"
    stage_note="**Released.** \`futureagi==$PY\` is on [PyPI](https://pypi.org/project/futureagi/$PY/) and \`@future-agi/sdk@$TS\` on [npm](https://www.npmjs.com/package/@future-agi/sdk/v/$TS); this PR is ready for review." ;;
  candidate)
    title="docs(sdk): platform SDK reference for python-v$PY / typescript-v$TS (candidate)"
    stage_note="**Candidate (draft).** The SDK release is prepared but \`futureagi==$PY\` and \`@future-agi/sdk@$TS\` are not both installable yet. The publish workflow re-dispatches once they are, and this PR is marked ready then. Do not merge before." ;;
  *)
    title="docs(sdk): platform SDK reference preview of futureagi-sdk@$short"
    stage_note="**Preview (draft).** Generated from \`$REF\`, which is not a published release. For looking only; the released PR for these versions is opened by the SDK publish workflow." ;;
esac

body_file=$(mktemp)
trap 'rm -f "$body_file"' EXIT
cat > "$body_file" <<EOF
Generated pages from [future-agi/futureagi-sdk@$short]($sdk/tree/$SHA/docs/sdk-reference): Python **$PY**, TypeScript **$TS**, backend contract **$BACKEND** (the SDK [sync PR]($sdk/pulls?q=is%3Apr+%22sync+with+backend+$BACKEND%22) names the backend release).

$stage_note

Copied by \`scripts/sync-sdk-reference.mjs\`; decided by \`scripts/sdk-reference-release.mjs\`; opened by \`scripts/sdk-reference-pr.sh\`. Do not edit the pages here: fix the generator in the SDK repository and re-run the sync. Source: $SOURCE
EOF

if [ -z "$number" ]; then
  draft=""
  [ "$PUBLISH" = draft ] && draft="--draft"
  # shellcheck disable=SC2086
  gh pr create --base main --head "$BRANCH" --title "$title" --body-file "$body_file" $draft >/dev/null
  read -r number is_draft <<< "$(existing)"
  [ -n "$number" ] || { echo "::error::the PR for $BRANCH was not created" >&2; exit 1; }
else
  gh pr edit "$number" --title "$title" --body-file "$body_file" >/dev/null
fi

# Make the real PR state match the decision, and prove it.
if [ "$PUBLISH" = ready ] && [ "$is_draft" = true ]; then
  gh pr ready "$number" || { echo "::error::could not mark future-agi/docs#$number ready for review" >&2; exit 1; }
fi
final=$(state_of "$number")
want=false
[ "$PUBLISH" = draft ] && want=true
if [ "$final" != "$want" ]; then
  echo "::error::future-agi/docs#$number isDraft=$final after this run, expected $want ($STAGE, $PUBLISH)" >&2
  exit 1
fi
state=ready
[ "$final" = true ] && state=draft
echo "future-agi/docs#$number ($STAGE, $state)"
